"""results/crypto_results.md and the by-month figure, written from the run only."""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from .crypto import FEE_BPS, MIN_TRAIN_DAYS, QUIET_DAYS  # noqa: E402
from .report import INK, INK2, SERIES, SURFACE, _style, pct  # noqa: E402



def nasdaq_comparison():
    """The Nasdaq one-tick-stock result, read from results/results.json if it exists."""
    import json
    p = Path(__file__).resolve().parents[2] / "results" / "results.json"
    if not p.exists():
        return None
    r = json.loads(p.read_text())
    return {t: r["predictive"][t]["Both|5"]["r2"] for t in ("INTC", "MSFT")}


def write(r, md_path, fig_dir):
    L = []
    w = L.append
    sym, dates = r["symbol"], r["dates"]
    w(f"# Results: {sym} perpetual, Binance USD-M futures\n")
    w("Generated by `run_crypto.py` from `results/crypto_results.json`. Do not edit by hand.\n")
    w(f"Data: Tardis.dev `quotes` (best bid and ask on every change) for the first day of each month, "
      f"{dates[0]} to {dates[-1]}, {len(dates)} days. Times are when each update was received.\n")

    w("## 0. Data checks\n")
    w("| Day | Updates | Empty side dropped | Crossed dropped | Receipt time went backwards | "
      "Median spread (ticks) | Time at one tick | One tick in bp | Mean depth at best |")
    w("|---|---|---|---|---|---|---|---|---|")
    tot = 0
    for d in dates:
        x = r["days"][d]
        tot += x["rows"]
        w(f"| {d} | {x['rows']:,} | {x['dropped_empty_side']:,} | {x['dropped_crossed']:,} | {x['time_backwards']:,} | "
          f"{x['median_spread_ticks']:.0f} | {pct(x['share_one_tick'])} | {x['tick_bps']:.4f} | {x['mean_depth']:.3f} |")
    w(f"\nTotal {tot:,} updates.\n")

    w("## 1. Same-interval fit (Cont, Kukanov and Stoikov setup)\n")
    c = [r["days"][d]["cks_r2"] for d in dates]
    w(f"Mean R² of 10-second mid change on 10-second OFI, half-hour windows: {pct(np.nanmean(c))} on average "
      f"(lowest day {pct(np.nanmin(c))}, highest {pct(np.nanmax(c))}).\n")

    w("## 2. Prediction out of sample, across months\n")
    w(f"Expanding window by day: fit on every earlier day, test on the next one, from day {MIN_TRAIN_DAYS + 1} on "
      f"({len(dates) - MIN_TRAIN_DAYS} test days). R² against a forecast of no change, pooled over test days; "
      "95% intervals resample test days. Hit rate is averaged over test days and counts only seconds where the mid moved.\n")
    w("| Model | h | Out-of-sample R² (%) | 95% CI | Test days with R² > 0 | R² without the 3 quiet days (%) | Hit rate |")
    w("|---|---|---|---|---|---|---|")
    for key, v in r["pred"].items():
        name, h = key.split("|")
        w(f"| {name} | {h}s | {100 * v['r2']:.2f} | [{100 * v['r2_ci'][0]:.2f}, {100 * v['r2_ci'][1]:.2f}] | "
          f"{pct(v['share_days_positive'], 0)} | {100 * v['r2_other_days']:.2f} | {pct(v['hit'])} |")
    nq = nasdaq_comparison()
    if nq:
        w(f"\nFor comparison, the Nasdaq one-tick stocks reached {100 * nq['INTC']:.2f}% (INTC) and "
          f"{100 * nq['MSFT']:.2f}% (MSFT) at 5 s on 21 June 2012.\n")

    w("## 3. Three quiet days\n")
    one = {x["date"]: x["r2"] for x in r["pred"]["Queue imbalance|1"]["by_day"]}
    w("The three test days where queue imbalance has a negative 1-second R² ("
      + ", ".join(f"{d} {100 * one[d]:.2f}%" for d in QUIET_DAYS) + ") are the three quietest. "
      "The table below is queue imbalance 5 s ahead. 'Slope' regresses the realised move on the forecast for that day: 1 means the "
      "forecasts were the right size, below 1 means they were too large. Mean move is the average absolute 5-second "
      "mid change in ticks.\n")
    w("| Test day | Weekday | Mean move (ticks) | R² (%) | Hit rate | Slope | Slope, activity-scaled model |")
    w("|---|---|---|---|---|---|---|")
    import datetime as _dt
    a = r["pred"]["Queue imbalance|5"]["by_day"]
    b = r["pred"]["Queue imbalance x recent activity|5"]["by_day"]
    for x, y in zip(a, b):
        tag = " (quiet)" if x["date"] in QUIET_DAYS else ""
        w(f"| {x['date']}{tag} | {_dt.date.fromisoformat(x['date']).strftime('%a')} | {x['mean_abs_move']:.1f} | "
          f"{100 * x['r2']:.2f} | {pct(x['hit'])} | {x['slope']:.2f} | {y['slope']:.2f} |")
    q = [x for x in a if x["date"] in QUIET_DAYS]
    o = [x for x in a if x["date"] not in QUIET_DAYS]
    w(f"\nOn the three quiet days the mid moved {np.mean([x['mean_abs_move'] for x in q]):.1f} ticks in 5 s on average, "
      f"against {np.mean([x['mean_abs_move'] for x in o]):.1f} on the other days, so forecasts sized on busier months "
      f"were too large (slopes {', '.join('%.2f' % x['slope'] for x in q)}) "
      f"even though the direction was right more often than usual (hit rates "
      f"{', '.join(pct(x['hit']) for x in q)}).\n")
    w("The activity-scaled model multiplies queue imbalance by the mean absolute 1-second mid change over the previous "
      "5 minutes. It was added after this first run had shown the problem, so it was chosen with the test days in view; "
      "only one version was tried. Its result is in the table in section 2.\n")

    w("## 4. Does it pay?\n")
    w(f"A taker trades the sign of the forecast when it clears a threshold set from the training days, crossing the "
      f"spread on entry and exit and paying the regular-account taker fee of {FEE_BPS['taker']:.0f} bp each way. "
      "Basis points per round trip, test days only.\n")
    for h, rows in r["costs"].items():
        w(f"**h = {h} s**\n")
        w("| In-sample top share | Trades | Gross move captured | Spread | Taker fees | Net |")
        w("|---|---|---|---|---|---|")
        for x in rows:
            w(f"| {pct(x['top_share'], 0)} | {x['trades']:,} | {x['gross_bps']:.3f} | {x['spread_bps']:.3f} | "
              f"{x['taker_fees_bps']:.1f} | {x['net_bps']:.2f} |")
        w("")
    w(f"Even a maker paying the regular {FEE_BPS['maker']:.0f} bp fee each way would need the gross move to clear "
      f"{2 * FEE_BPS['maker']:.0f} bp per round trip.\n")
    w(f"Runtime {r['runtime_s']:.0f} s.\n")
    Path(md_path).write_text("\n".join(L))

    # figure: out-of-sample R^2 at 5 s by test day
    fig, ax = plt.subplots(figsize=(8, 3.8))
    for name, col, lab in [("Queue imbalance", SERIES[0], "Queue imbalance"),
                           ("Queue imbalance x recent activity", SERIES[1], "Queue imbalance x recent activity (added after the first run)")]:
        bd = r["pred"][f"{name}|5"]["by_day"]
        ax.plot(range(len(bd)), [100 * b["r2"] for b in bd], marker="o", markersize=5, linewidth=2,
                color=col, label=lab)
        labels = [b["date"][:7] for b in bd]
    ax.axhline(0, color=INK2, linewidth=0.8)
    step = max(1, len(labels) // 8)
    ax.set_xticks(range(0, len(labels), step), labels[::step])
    ax.set_ylabel("Out-of-sample R², 5 s ahead (%)")
    ax.set_title(f"{sym}: forecast skill on each held-out month", loc="left", fontsize=11)
    _style(ax); ax.legend(frameon=False, fontsize=9, loc="best")
    fig.tight_layout(); Path(fig_dir).mkdir(exist_ok=True)
    fig.savefig(Path(fig_dir) / "6_crypto_by_month.png", dpi=160); plt.close(fig)
