"""Turn results.json into results.md and the figures. No numbers are typed here."""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from . import features as F  # noqa: E402
from . import io  # noqa: E402

PAPER = {"r2_ofi": 0.65, "r2_ti": 0.32, "lambda": 0.98}
# Nasdaq Rule 7018, SR-NASDAQ-2012-053: credit for adding displayed liquidity
# $0.0020 to $0.00295 per share, charge for removing $0.0030. One tick = $0.01.
REBATE_TICKS = (0.20, 0.295)
TAKE_FEE_TICKS = 0.30

# reference categorical palette, light mode, fixed order (see README)
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def ci(c, d=2):
    return f"[{100 * c[0]:.{d}f}, {100 * c[1]:.{d}f}]"


def write_markdown(r, path):
    T = r["tickers"]
    L = []
    w = L.append
    w("# Results\n")
    w("Generated by `run_all.py` from `results/results.json`. Do not edit by hand.\n")
    w("Data: LOBSTER Nasdaq sample day, 21 June 2012, every message plus the best bid and ask.\n")

    w("## 0. Data checks\n")
    w("| Stock | Messages | Shared timestamps | Crossed or empty book | Level-1 replays every message |")
    w("|---|---|---|---|---|")
    for t in T:
        d = r["data"][t]
        w(f"| {t} | {d['messages']:,} | {d['rows_sharing_a_timestamp']:,} | "
          f"{d['crossed_or_locked'] + d['empty_side_rows']} | {pct(d['l1_consistent_share'], 2)} |")
    tot = sum(r["data"][t]["messages"] for t in T)
    w(f"\nTotal {tot:,} messages.\n")

    rp = r["replication"]
    w("## 1. Replication of Cont, Kukanov and Stoikov (2014)\n")
    w("Mid-price change in ticks on OFI over 10-second intervals, one OLS per half-hour window "
      "(13 windows per stock, about 180 intervals each), as in the paper.\n")
    w("| Stock | Median spread (ticks) | Mean depth at best (shares) | Mean R² on OFI | Mean R² on trade imbalance | Windows with significant beta |")
    w("|---|---|---|---|---|---|")
    for t in T:
        x = rp[t]
        w(f"| {t} | {r['predictive'][t]['spread_median']:.0f} | {x['mean_depth']:,.0f} | {pct(x['mean_r2_ofi'])} | "
          f"{pct(x['mean_r2_ti'])} | {x['share_beta_significant'] * 13:.0f} of 13 |")
    p = rp["_pooled"]
    w(f"| **Average** | | | **{pct(p['mean_r2_ofi'])}** | **{pct(p['mean_r2_ti'])}** | |")
    w(f"| Paper (50 stocks, April 2010) | | | {pct(PAPER['r2_ofi'], 0)} | {pct(PAPER['r2_ti'], 0)} | |\n")
    w(f"Depth exponent: regressing log beta on log average depth with stock fixed effects gives "
      f"lambda = {p['lambda']:.2f} (standard error {p['lambda_se']:.2f}, {p['lambda_n']} windows), "
      f"against {PAPER['lambda']} in the paper. Price impact per share is close to inversely proportional to depth.\n")
    g0 = rp["GOOG"]
    w(f"Lowest window: GOOG {pct(g0['min_r2_ofi'])} in window {g0['min_window']} (09:30 to 10:00), "
      f"when its median spread was {r['predictive']['GOOG']['open_spread_median']:.0f} ticks, "
      f"against {r['predictive']['GOOG']['spread_median']:.0f} over the whole day.\n")

    w("## 2. Prediction out of sample\n")
    w("1-second grid. Features use only events up to t; the label is the mid-price change over (t, t+h] in ticks. "
      "Walk-forward by half-hour block (train on all earlier blocks, test on the next, 11 test blocks), "
      "with training rows whose label reaches into the test block dropped. "
      "R² is against a forecast of no change. Hit rate counts only intervals where the mid moved. "
      "95% intervals from a 5-minute moving-block bootstrap.\n")
    w("**Model with queue imbalance and lagged OFI**\n")
    w("| Stock | h | Mid unchanged | Out-of-sample R² (%) | 95% CI | Hit rate | 95% CI |")
    w("|---|---|---|---|---|---|---|")
    for t in T:
        for h in [1, 5, 30]:
            x = r["predictive"][t][f"Both|{h}"]
            w(f"| {t} | {h}s | {pct(r['predictive'][t][f'zero_share_{h}s'], 0)} | {100 * x['r2']:.2f} | {ci(x['r2_ci'])} | "
              f"{pct(x['hit'])} | {ci(x['hit_ci'], 1)} |")
    w("\n**Which feature carries it** (out-of-sample R², %, h = 5 s)\n")
    w("| Stock | Queue imbalance only | Lagged OFI only | Both |")
    w("|---|---|---|---|")
    for t in T:
        a = [r["predictive"][t][f"{m}|5"]["r2"] for m in ("Queue imbalance", "Lagged OFI", "Both")]
        w(f"| {t} | " + " | ".join(f"{100 * v:.2f}" for v in a) + " |")

    w("\n## 3. What a one-second timestamp leak does\n")
    w("Same 1-second OFI feature, same walk-forward. The leaky version bins events by floor(time) and labels each bin "
      "by its left edge, so the value 'at t' contains events from (t, t+1s).\n")
    w("| Stock | h | Clean R² (%) | Leaky R² (%) | Clean hit rate | Leaky hit rate |")
    w("|---|---|---|---|---|---|")
    for t in T:
        for h in [1, 5]:
            x = r["leak"][t][str(h)] if str(h) in r["leak"][t] else r["leak"][t][h]
            w(f"| {t} | {h}s | {100 * x['clean_r2']:.2f} | {100 * x['leaky_r2']:.1f} | {pct(x['clean_hit'])} | {pct(x['leaky_hit'])} |")

    w("\n## 4. Transfer across stocks (out-of-sample R², %, h = 5 s)\n")
    w("Rows: fitted on that stock from 09:30 to 13:00. Columns: tested on that stock from 13:00 to 16:00, "
      "so no test minute overlaps a training minute.\n")
    tr = r["transfer"]["5"] if "5" in r["transfer"] else r["transfer"][5]
    names = tr["names"]
    w("| Fitted on \\ tested on | " + " | ".join(names) + " |")
    w("|---|" + "---|" * len(names))
    for i, a in enumerate(names):
        w(f"| {a} | " + " | ".join(f"{100 * v:.2f}" for v in tr["r2"][i]) + " |")

    w("\n## 5. Does it pay a taker?\n")
    w("Trade the sign of the forecast at t when its size clears a threshold, cross the spread "
      "to enter at t and again to exit at t + h. Thresholds are quantiles of the in-sample forecasts from the same "
      "walk-forward step, so the rule could have been set before each test block. 'Top 1%' is therefore the in-sample "
      "top 1%; the share of test rows that trade can differ. Ticks per trade, out of sample.\n")
    for h in [5, 30]:
        w(f"**h = {h} s**\n")
        w("| Stock | In-sample top share | Trades | Gross move captured | Spread paid | Net | Gross as share of cost |")
        w("|---|---|---|---|---|---|---|")
        for t in T:
            rows = r["costs"][t][str(h)] if str(h) in r["costs"][t] else r["costs"][t][h]
            for row in rows:
                if row["top_share"] in (1.0, 0.1, 0.01) or abs(row["top_share"] - 0.1) < 1e-9 or abs(row["top_share"] - 0.01) < 1e-9:
                    w(f"| {t} | {pct(row['top_share'], 0)} | {row['trades']:,} | {row['gross']:.3f} | {row['cost']:.2f} | "
                      f"{row['net']:.2f} | {pct(row['gross_over_cost'], 0)} |")
        w("")
    best = max(((row["gross_over_cost"], t, h, row["top_share"]) for t in T for h in r["costs"][t]
                for row in r["costs"][t][h]), key=lambda z: z[0])
    any_net_positive = any(row["net"] > 0 for t in T for h in r["costs"][t] for row in r["costs"][t][h])
    w(f"Best case over every stock, horizon (1, 5 and 30 s) and threshold: {best[1]}, h = {best[2]} s, "
      f"in-sample top {pct(best[3], 0)}, where the move covers {pct(best[0], 0)} of the spread paid. "
      f"Any combination with positive net: {'yes' if any_net_positive else 'no'}.\n")
    w(f"Nasdaq also charged takers $0.0030 a share in 2012, {TAKE_FEE_TICKS:.2f} ticks on each side, "
      "which this section leaves out. Including it would only widen the gap.\n")

    write_maker_markdown(r, w)
    w(f"Runtime {r['runtime_s']:.0f} s.\n")
    Path(path).write_text("\n".join(L))


def write_maker_markdown(r, w):
    MK = r["maker"]
    H = [1, 5, 30, 60]
    w("## 6. Market making with queue position (INTC, MSFT)\n")
    w("A maker quotes 100 shares at the best bid and the best ask, rejoins at the back of the queue after each fill, "
      "and holds at most 1,000 shares either way. Queue position is tracked order by order from the LOBSTER order IDs "
      "under first-in-first-out priority (see `src/lobofi/maker.py`). Each fill is marked to the mid-price h seconds "
      "later, in ticks per share; positive is good for the maker. 'Edge at fill' is the half-spread earned against the "
      "mid just before the fill. Nasdaq paid makers a rebate of "
      f"{REBATE_TICKS[0]:.2f} to {REBATE_TICKS[1]:.3f} ticks a share in 2012, so a fill breaks even after rebate when "
      f"its markout is above -{REBATE_TICKS[1]:.3f} at the top tier.\n")
    w("**Queue model, 09:35 to 15:55**\n")
    w("| Stock | Queue model | Shares filled | Edge at fill | " + " | ".join(f"Markout {h}s" for h in H) + " |")
    w("|---|---|---|---|" + "---|" * len(H))
    names = {"front": "Ignore the queue (front of queue)", "queue": "Queue-aware",
             "queue_orphan_cancel": "Queue-aware, optimistic on emptied levels"}
    for t in MK:
        for k in ("front", "queue", "queue_orphan_cancel"):
            b = MK[t]["baseline"][k]
            w(f"| {t} | {names[k]} | {b['shares']:,} | {b['edge_at_fill']:.3f} | "
              + " | ".join(f"{b[f'markout_{h}s']:.3f}" for h in H) + " |")
    w("")
    for t in MK:
        b = MK[t]["baseline"]
        w(f"- {t}: ignoring the queue fills {b['front']['shares'] / b['queue']['shares']:.2f} times as many shares "
          f"and makes each look {b['front']['markout_30s'] - b['queue']['markout_30s']:.3f} ticks better at 30 s. "
          f"Queue-aware fills lose {-b['queue']['markout_30s']:.3f} ticks a share at 30 s "
          f"({-b['queue_orphan_cancel']['markout_30s']:.3f} under the optimistic rule), against a top rebate of {REBATE_TICKS[1]:.3f}.")
    w("")
    w("**Pulling quotes on queue imbalance.** Pull the bid when queue imbalance is below -theta, the ask when it is "
      "above theta. Theta is chosen on the morning (09:35 to 13:00) by 30-second markout per share and then run once "
      "on the afternoon (13:00 to 15:55). 95% intervals resample 5-minute buckets of fills. Zero latency.\n")
    w("| Stock | Theta | Morning shares | Morning markout 30s | Afternoon shares | Afternoon markout 30s | 95% CI | Afternoon markout 5s |")
    w("|---|---|---|---|---|---|---|---|")
    for t in MK:
        for th, row in MK[t]["sweep"].items():
            m, a = row["morning"], row["afternoon"]
            tag = f"**{th}** (chosen)" if th == MK[t]["chosen_theta"] else th
            w(f"| {t} | {tag} | {m['shares']:,} | {m['markout_30s']:.3f} | {a['shares']:,} | {a['markout_30s']:.3f} | "
              f"[{a['ci_select'][0]:.3f}, {a['ci_select'][1]:.3f}] | {a['markout_5s']:.3f} |")
    w("")
    w("**Latency, afternoon, chosen theta**\n")
    w("| Stock | Latency | Shares | Markout 5s | Markout 30s | Joins dropped because the price moved |")
    w("|---|---|---|---|---|---|")
    for t in MK:
        for lat, v in MK[t]["latency"].items():
            w(f"| {t} | {lat} ms | {v['shares']:,} | {v['markout_5s']:.3f} | {v['markout_30s']:.3f} | {v['n_joins_dropped']} |")
    w("")
    for t in MK:
        sw = MK[t]["sweep"]; ch = MK[t]["chosen_theta"]
        off, on = sw["off"]["afternoon"], sw[ch]["afternoon"]
        l0, l1 = MK[t]["latency"]["0"], MK[t]["latency"]["0.5"]
        w(f"- {t}: on the held-out afternoon, pulling at theta {ch} changes the 30-second markout from "
          f"{off['markout_30s']:.3f} to {on['markout_30s']:.3f} and the 5-second markout from {off['markout_5s']:.3f} to "
          f"{on['markout_5s']:.3f}, while filling {pct(on['shares'] / off['shares'], 0)} of the shares. With 0.5 ms of "
          f"latency the 5-second markout is {l1['markout_5s']:.3f}.")
    w("")


def _style(ax):
    ax.set_facecolor(SURFACE)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=9)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def write_figures(r, frames, outdir):
    outdir = Path(outdir)
    outdir.mkdir(exist_ok=True)
    T = r["tickers"]
    plt.rcParams.update({"font.size": 10, "text.color": INK, "axes.labelcolor": INK2,
                         "figure.facecolor": SURFACE})

    # 1. replication bars
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    x = np.arange(len(T)); wdt = 0.36
    ofi = [r["replication"][t]["mean_r2_ofi"] for t in T]
    ti = [r["replication"][t]["mean_r2_ti"] for t in T]
    ax.bar(x - wdt / 2 - 0.01, ofi, wdt, color=SERIES[0], label="Order-flow imbalance")
    ax.bar(x + wdt / 2 + 0.01, ti, wdt, color=SERIES[1], label="Trade imbalance")
    ax.axhline(PAPER["r2_ofi"], color=SERIES[0], linestyle=(0, (4, 3)), linewidth=1.2)
    ax.axhline(PAPER["r2_ti"], color=SERIES[1], linestyle=(0, (4, 3)), linewidth=1.2)
    ax.text(len(T) - 0.45, PAPER["r2_ofi"] + 0.015, "paper 65%", color=INK2, fontsize=8, ha="right")
    ax.text(len(T) - 0.45, PAPER["r2_ti"] + 0.015, "paper 32%", color=INK2, fontsize=8, ha="right")
    for i, v in enumerate(ofi):
        ax.text(i - wdt / 2 - 0.01, v + 0.01, f"{100 * v:.0f}%", ha="center", fontsize=8, color=INK)
    ax.set_xticks(x, T); ax.set_ylim(0, 1); ax.set_ylabel("Mean R², 10 s intervals")
    ax.set_title("Same-interval price change explained, by stock", loc="left", fontsize=11)
    _style(ax); ax.legend(frameon=False, fontsize=9, loc="upper left")
    fig.tight_layout(); fig.savefig(outdir / "1_replication.png", dpi=160); plt.close(fig)

    # 2. OFI vs price change, MSFT, 10 s intervals
    df = io.load("MSFT")
    g = F.grid(io.OPEN + 10, io.CLOSE + 5, 10.0)
    s = F.sample(*io.book_arrays(df), g)
    dp = np.diff(F.mid_ticks(s)); ofi10 = np.diff(s["cumofi"]) / 1000.0
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.scatter(ofi10, dp, s=10, color=SERIES[0], alpha=0.35, edgecolors="none")
    ax.set_xlabel("OFI over 10 s (thousand shares)"); ax.set_ylabel("Mid-price change (ticks)")
    ax.set_title("MSFT, 21 June 2012, every 10 s interval", loc="left", fontsize=11)
    _style(ax); fig.tight_layout(); fig.savefig(outdir / "2_msft_scatter.png", dpi=160); plt.close(fig)

    # 3. out-of-sample R2 by horizon
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    hs = [1, 5, 30]; x = np.arange(len(hs)); wdt = 0.15
    for i, t in enumerate(T):
        vals = [r["predictive"][t][f"Both|{h}"] for h in hs]
        y = [100 * v["r2"] for v in vals]
        err = np.array([[100 * (v["r2"] - v["r2_ci"][0]), 100 * (v["r2_ci"][1] - v["r2"])] for v in vals]).T
        ax.bar(x + (i - 2) * (wdt + 0.01), y, wdt, color=SERIES[i], label=t,
               yerr=err, error_kw={"ecolor": INK2, "elinewidth": 0.8, "capsize": 2})
    ax.axhline(0, color=INK2, linewidth=0.8)
    ax.set_xticks(x, [f"{h} s ahead" for h in hs]); ax.set_ylabel("Out-of-sample R² (%)")
    ax.set_title("Forecasting the next mid-price move, with 95% intervals", loc="left", fontsize=11)
    _style(ax); ax.legend(frameon=False, fontsize=9, ncol=5, loc="upper left")
    fig.tight_layout(); fig.savefig(outdir / "3_oos_r2.png", dpi=160); plt.close(fig)

    # 4. costs, large-tick stocks
    fig, ax = plt.subplots(figsize=(6.5, 3.8))
    for i, t in enumerate(["INTC", "MSFT"]):
        rows = r["costs"][t][5]
        xs = [100 * row["top_share"] for row in rows]
        ax.plot(xs, [row["gross"] for row in rows], marker="o", markersize=5, linewidth=2,
                color=SERIES[i], label=f"{t}, move captured")
    ax.axhline(1.0, color=INK2, linestyle=(0, (4, 3)), linewidth=1.2)
    ax.text(60, 1.03, "spread paid, about 1 tick", color=INK2, fontsize=8)
    ax.set_xscale("log"); ax.invert_xaxis(); ax.minorticks_off()
    ax.set_xticks([100, 50, 20, 10, 5, 1], ["all", "top 50%", "top 20%", "top 10%", "top 5%", "top 1%"])
    ax.set_ylim(0, 1.2); ax.set_ylabel("Ticks per trade, 5 s holding")
    ax.set_xlabel("Signal threshold, set from in-sample forecasts")
    ax.set_title("The edge is real but smaller than the spread", loc="left", fontsize=11)
    _style(ax); ax.legend(frameon=False, fontsize=9, loc="center left")
    fig.tight_layout(); fig.savefig(outdir / "4_costs.png", dpi=160); plt.close(fig)

    # 5. maker markouts, afternoon
    MK = r["maker"]
    H = [1, 5, 30, 60]
    fig, axes = plt.subplots(1, len(MK), figsize=(9, 3.9), sharey=True)
    for ax, t in zip(np.atleast_1d(axes), MK):
        ch = MK[t]["chosen_theta"]
        lines = [("Ignoring the queue", MK[t]["afternoon_front"], SERIES[1]),
                 ("Queue-aware", MK[t]["sweep"]["off"]["afternoon"], SERIES[0]),
                 ("Queue-aware, pulling on imbalance", MK[t]["sweep"][ch]["afternoon"], SERIES[2])]
        ax.axhspan(-REBATE_TICKS[1], -REBATE_TICKS[0], color=GRID, alpha=0.9, linewidth=0)
        ax.text(0.98, -REBATE_TICKS[0] + 0.03, "break-even at Nasdaq rebate", transform=ax.get_yaxis_transform(),
                ha="right", fontsize=8, color=INK2)
        ax.axhline(0, color=INK2, linewidth=0.8)
        for name, v, col in lines:
            ax.plot(range(len(H)), [v[f"markout_{h}s"] for h in H], marker="o", markersize=5, linewidth=2,
                    color=col, label=name)
        ax.set_xticks(range(len(H)), [f"{h} s" for h in H])
        ax.set_title(f"{t}, 13:00 to 15:55, theta {ch}", loc="left", fontsize=10)
        ax.set_ylim(-0.8, 0.1)
        _style(ax)
    np.atleast_1d(axes)[0].set_ylabel("Fill marked to mid, ticks per share")
    np.atleast_1d(axes)[0].legend(frameon=False, fontsize=8, loc="lower left")
    fig.suptitle("Market-maker fills lose more than the rebate pays", x=0.01, ha="left", fontsize=11)
    fig.tight_layout(); fig.savefig(outdir / "5_maker_markouts.png", dpi=160); plt.close(fig)
